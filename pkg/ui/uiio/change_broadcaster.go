package uiio

import "github.com/fmstephe/simd_explorer/pkg/assembly"

type changeBroadcaster struct {
	inst      assembly.Instruction
	active    bool
	receivers []*UIParameters
}

func newChangeBroadcaster(inst assembly.Instruction) *changeBroadcaster {
	return &changeBroadcaster{
		inst:      inst,
		active:    true,
		receivers: []*UIParameters{},
	}
}

func (b *changeBroadcaster) addReceiver(r *UIParameters) {
	b.receivers = append(b.receivers, r)
}

func (b *changeBroadcaster) broadcastZeros() {
	// Resets all parts to zero
	params := b.inst.Inputs()
	zeroVals := make([][]byte, len(params))
	for i, param := range params {
		zeroVals[i] = make([]byte, param.TotalBitWidth()/8)
	}
	b.broadcastChange(zeroVals)
}

func (b *changeBroadcaster) broadcastChange(inputs [][]byte) {
	if !b.active {
		return
	}

	// Disable change eventbroadcasts generated by this update, this prevents ping/pong updates
	b.deactivate()
	defer b.activate()

	output := b.inst.Run(inputs)

	for _, r := range b.receivers {
		r.setData(inputs, output)
	}
}

func (b *changeBroadcaster) activate() {
	b.active = true
}

func (b *changeBroadcaster) deactivate() {
	b.active = false
}
